const fallbackKey = "aura";
const params = new URLSearchParams(window.location.search);
const key = directions[params.get("d")] ? params.get("d") : fallbackKey;
const data = directions[key];
const directionUrl = `alisa-direction.html?d=${key}`;
const galleryUrl = `alisa-gallery.html?d=${key}`;

document.title = `Алеся Кузьмич — ${data.title}${document.body.dataset.page === "gallery" ? " — галерея" : ""}`;

document.querySelectorAll("[data-field]").forEach((element) => {
  const field = element.dataset.field;

  if (field === "title") {
    element.textContent = data.title;
  }

  if (field === "lead") {
    element.textContent = data.lead;
  }

  if (field === "description") {
    element.textContent = data.richContent ? "" : data.description;
    element.hidden = Boolean(data.richContent);
  }

  if (field === "richContent") {
    element.innerHTML = data.richContent || "";
    element.hidden = !data.richContent;
  }

  if (field === "photoPair") {
    element.hidden = Boolean(data.richContent);
  }

  if (field === "galleryLink") {
    element.href = galleryUrl;
  }

  if (field === "descriptionLink" || field === "backToDirection") {
    element.href = directionUrl;
  }

  if (field === "reviewsLink") {
    element.href = `${directionUrl}#reviews`;
  }

  if (field === "pricesLink") {
    element.href = `${directionUrl}#prices`;
  }

  if (field === "reviews") {
    element.innerHTML = data.reviews
      .map((review) => `<blockquote>${review}</blockquote>`)
      .join("");
  }

  if (field === "prices") {
    element.innerHTML = data.prices.map((price) => `<article>${price}</article>`).join("");
  }
});
